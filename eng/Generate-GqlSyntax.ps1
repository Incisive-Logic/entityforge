param(
    [string] $AntlrJar,
    [string] $Java = 'java',
    [switch] $IdentifiersOnly
)

$ErrorActionPreference = 'Stop'
if (!$IdentifiersOnly) {
$jar = (Resolve-Path -LiteralPath $AntlrJar).Path
$expected = 'BC13A9C57A8DD7D5196888211E5EDE657CB64A3CE968608697E4F668251A8487'
if ((Get-FileHash -LiteralPath $jar -Algorithm SHA256).Hash -ne $expected) {
    throw 'Use the unmodified antlr-4.13.1-complete.jar from https://www.antlr.org/download/.'
}
}
$target = Join-Path $PSScriptRoot '../src/Db/EntityForge.Db.Query.Syntax/Gql'
$unicode = Join-Path $PSScriptRoot '../src/Db/EntityForge.Db.Query.Planning/Unicode'
$expectedUnicode = @{
    'DerivedCoreProperties-16.0.0.txt' = '39D35161F2954497F69E08BDB9E701493F476A3D30222DE20028FEDA36C1DABD'
    'UnicodeData-16.0.0.txt' = 'FF58E5823BD095166564A006E47D111130813DCF8BF234EF79FA51A870EDB48F'
}
foreach ($name in $expectedUnicode.Keys) {
    if ((Get-FileHash -LiteralPath (Join-Path $unicode $name) -Algorithm SHA256).Hash -ne $expectedUnicode[$name]) {
        throw "Pinned Unicode 16 data hash mismatch: $name"
    }
}
$coreRows = Get-Content -LiteralPath (Join-Path $unicode 'DerivedCoreProperties-16.0.0.txt')
$categoryRows = Get-Content -LiteralPath (Join-Path $unicode 'UnicodeData-16.0.0.txt')
function Read-CoreRanges([string] $property) {
    foreach ($line in $coreRows) {
        if ($line -match ('^([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*;\s*' + $property + '\s*(?:#|$)')) {
            $first = [Convert]::ToInt32($Matches[1], 16)
            $last = if ($Matches[2]) { [Convert]::ToInt32($Matches[2], 16) } else { $first }
            [pscustomobject]@{ First = $first; Last = $last }
        }
    }
}
function Read-CategoryRanges([string] $category) {
    foreach ($line in $categoryRows) {
        $fields = $line.Split(';')
        if ($fields[2] -eq $category) {
            $point = [Convert]::ToInt32($fields[0], 16)
            [pscustomobject]@{ First = $point; Last = $point }
        }
    }
}
function Render-Class($ranges, [bool] $bmpOnly = $false) {
    function Escape-Point([int] $point) {
        if ($point -le 0xFFFF) { return '\u' + $point.ToString('X4') }
        return '\u{' + $point.ToString('X') + '}'
    }
    $parts = foreach ($range in $ranges) {
        if ($bmpOnly -and $range.First -gt 0xFFFF) { continue }
        $last = if ($bmpOnly) { [Math]::Min($range.Last, 0xFFFF) } else { $range.Last }
        $text = Escape-Point $range.First
        if ($last -ne $range.First) { $text += '-' + (Escape-Point $last) }
        $text
    }
    return [string]::Concat($parts)
}
$ranges = @{
    ID_Start = @(Read-CoreRanges 'ID_Start')
    ID_Continue = @(Read-CoreRanges 'ID_Continue')
    Pc = @(Read-CategoryRanges 'Pc')
    Sc = @(Read-CategoryRanges 'Sc')
}
function Write-NativeIdentifiers {
    $start = (Render-Class ($ranges.ID_Start + $ranges.Pc) $true) + '\uD800-\uDFFF'
    $continuation = (Render-Class $ranges.ID_Continue $true) + '\uD800-\uDFFF'
    $native = @"
// <auto-generated />
// Unicode 16 identifier sets. Generated by eng/Generate-GqlSyntax.ps1.
// Unicode data licence: src/Db/EntityForge.Db.Query.Planning/Unicode/LICENSE.txt.
namespace EntityForge.Db.Gql;

internal static partial class GraphGqlIdentifiers
{
    internal const string Start = @"[$start]";
    internal const string Continuation = @"[$continuation]";
}
"@
    [IO.File]::WriteAllText((Join-Path $PSScriptRoot '../src/Db/EntityForge.Db.Gql/GraphGqlIdentifiers.Unicode.generated.cs'), $native)
}
if ($IdentifiersOnly) { Write-NativeIdentifiers; return }
$grammar = [IO.File]::ReadAllText((Join-Path $target 'GQL.g4'))
foreach ($property in $ranges.Keys) {
    # ANTLR's bundled Unicode version is independent of the selected GQL version.
    # Expand properties in a temporary grammar; retain the readable source grammar.
    $grammar = $grammar.Replace('[\p{' + $property + '}]', '[' + (Render-Class $ranges[$property]) + ']')
    $grammar = $grammar.Replace('fragment ' + $property, 'fragment ' + $property + ' options { caseInsensitive=false; }')
}
$temporary = [IO.Directory]::CreateTempSubdirectory('entityforge-gql-').FullName
try {
    [IO.File]::WriteAllText((Join-Path $temporary 'GQL.g4'), $grammar)
    Push-Location $temporary
    try {
        & $Java -jar $jar -Dlanguage=CSharp -package EntityForge.Db.Query.Syntax.Gql -no-listener -o $temporary GQL.g4
        if ($LASTEXITCODE -ne 0) { throw 'ANTLR generation failed.' }
    }
    finally { Pop-Location }
    foreach ($name in @('GQLLexer', 'GQLParser')) {
        $text = [IO.File]::ReadAllText((Join-Path $temporary "$name.cs"))
        $text = $text.Replace("public partial class $name :", "internal partial class $name :").Replace('[System.CLSCompliant(false)]', '')
        [IO.File]::WriteAllText((Join-Path $target "$name.generated.cs"), $text)
    }
    Write-NativeIdentifiers
}
finally {
    # Only files generated in this invocation's unique temporary directory.
    Get-ChildItem -LiteralPath $temporary -File | Remove-Item -Force
    Remove-Item -LiteralPath $temporary
}
