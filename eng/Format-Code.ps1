#Requires -Version 7.4
[CmdletBinding()]
param([switch]$Verify)
$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot -Parent
Push-Location $root
try {
    $files = @(& git ls-files --cached --others --exclude-standard)
    if ($LASTEXITCODE) { throw 'Cannot enumerate source files.' }
    $files = @($files | Where-Object { Test-Path -LiteralPath $_ -PathType Leaf })
    $excluded = @($files | Where-Object {
        if ($_ -match '(?i)(/ThirdParty/|/Unicode/|/Fixtures/|/upstream/|/Gql/GQL\.g4$|FastWildcard\.cs$|\.generated\.cs$)') { return $true }
        if ($_.EndsWith('.cs') -and (Test-Path -LiteralPath $_)) {
            $header = Get-Content -LiteralPath $_ -TotalCount 25 | Out-String
            return $header -match '<auto-generated'
        }
        return $false
    })
    $common = @('EntityForge.slnx', '--no-restore', '--exclude') + $excluded
    if ($Verify) { $common += '--verify-no-changes' }
    # Restrict fixes to layout and braces. Never reorder members, change namespace
    # style, introduce primary constructors or apply unrelated analyzer fixes.
    foreach ($pass in @(
        @{ Command = 'style'; Extra = @('--diagnostics', 'IDE0011', '--severity', 'error') },
        @{ Command = 'analyzers'; Extra = @('--diagnostics', 'SA1107', 'SA1500', 'SA1501', 'SA1502', 'SA1503', 'SA1516', 'SA1028', '--severity', 'warn') },
        @{ Command = 'whitespace'; Extra = @() }
    )) {
        & dotnet format $pass.Command @common @($pass.Extra)
        if ($LASTEXITCODE) { throw "Formatting $($pass.Command) failed; inspect the diagnostics above." }
    }
    foreach ($relative in $files | Where-Object { $_.EndsWith('.cs') -and $_ -notin $excluded }) {
        $path = Join-Path $root $relative
        $text = [IO.File]::ReadAllText($path)
        $formatted = $text.TrimEnd([char[]]"`r`n `t") + "`n"
        if ($text -cne $formatted) {
            if ($Verify) { throw "Extra end-of-file whitespace: $relative" }
            [IO.File]::WriteAllText($path, $formatted, [Text.UTF8Encoding]::new($false))
        }
    }
    # Project XML has no executable C# literals. Preserve its XML structure while
    # writing consistent indentation/newlines; do not process imported fixtures.
    foreach ($relative in $files | Where-Object { $_ -match '\.(csproj|props|targets)$' -and $_ -notin $excluded }) {
        $path = Join-Path $root $relative
        $document = [System.Xml.Linq.XDocument]::Load($path)
        $settings = [System.Xml.XmlWriterSettings]::new()
        $settings.Indent = $true
        $settings.IndentChars = '    '
        $settings.NewLineChars = "`n"
        $settings.OmitXmlDeclaration = $null -eq $document.Declaration
        $buffer = [IO.MemoryStream]::new()
        $settings.Encoding = [Text.UTF8Encoding]::new($false)
        $writer = [Xml.XmlWriter]::Create($buffer, $settings)
        try { $document.Save($writer); $writer.Flush(); $formatted = [Text.Encoding]::UTF8.GetString($buffer.ToArray()).TrimEnd() + "`n" }
        finally { $writer.Dispose(); $buffer.Dispose() }
        if (![System.Xml.Linq.XNode]::DeepEquals($document, [System.Xml.Linq.XDocument]::Parse($formatted))) { throw "XML structure changed: $relative" }
        if ([IO.File]::ReadAllText($path) -cne $formatted) {
            if ($Verify) { throw "Project XML formatting differs: $relative" }
            [IO.File]::WriteAllText($path, $formatted, [Text.UTF8Encoding]::new($false))
        }
    }
}
finally { Pop-Location }
