    [DataRow("RETURN null IS :: ANY<INTEGER | STRING> AS answer", "true")]
    public async Task Gql_scalar_values_and_case_expressions(string query, string expected)
    {
        _directory = NewDirectory();
        await using var host = EntityForgeDbServer.CreateBuilder().UseLocalStorage(_directory).UsePropertyGraphProfile()
            .ConfigureWebHost(web => web.UseUrls("http://127.0.0.1:0")).Build();
        await host.StartAsync();
        using var client = Client(host);
        using var response = await client.PostAsJsonAsync("/v1/graph/gql/query", new
        {
            query
        });
        Assert.AreEqual(expected == "ERROR" ? HttpStatusCode.BadRequest : HttpStatusCode.OK, response.StatusCode,
            await response.Content.ReadAsStringAsync());
        if (expected != "ERROR")
        {
            var result = await response.Content.ReadFromJsonAsync<JsonElement>();
            var value = result.GetProperty("matches")[0].GetProperty("bindings").GetProperty("answer");
            if (value.ValueKind == JsonValueKind.String)
            {
                Assert.AreEqual(JsonSerializer.Deserialize<string>(expected), value.GetString());
            }
            else
            {
                Assert.AreEqual(expected, value.GetRawText());
            }
        }
    }

