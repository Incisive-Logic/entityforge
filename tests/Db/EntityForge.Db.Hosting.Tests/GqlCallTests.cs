    [TestMethod]
    [DataRow("1", "1")]
    [DataRow("\"display name\"", "display name")]
    [DataRow("`display name`", "display name")]
    [DataRow("`match`", "match")]
    [DataRow("`a``b`", "a`b")]
    [DataRow("\"a\"\"b\"", "a\"b")]
    [DataRow("`a//b`", "a//b")]
    [DataRow("`a/*b*/$with`", "a/*b*/$with")]
    [DataRow("`a\"b`", "a\"b")]
    [DataRow("\"a\\u0020b\"", "a b")]
    public async Task Gql_separated_parameter_names_preserve_exact_keys(string spelling, string name)
    {
        var parameters = new Dictionary<string, object> { [name] = 7 };
        await AssertCallQuery("RETURN $" + spelling + " AS answer", "[7]", parameters);
        await AssertCallQuery("RETURN 1 AS n NEXT RETURN $" + spelling + "+n AS answer", "[8]", parameters);
        await AssertCallQuery("RETURN $" + spelling + " AS n UNION ALL RETURN 1 AS n NEXT RETURN SUM(n) AS answer", "[8]", parameters);
        await AssertCallQuery("MATCH ANY $" + spelling + " (a)((x)-[e]->(y)){1,2}(b) RETURN COUNT(*) AS answer", "[0]", parameters);
    }

