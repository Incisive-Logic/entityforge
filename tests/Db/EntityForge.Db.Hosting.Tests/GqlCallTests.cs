    [TestMethod]
    public async Task Gql_wildcard_composition_preserves_parameter_values()
    {
        var parameters = new Dictionary<string, object> { ["seed"] = 10, ["values"] = new[] { 2, 3 } };
        await AssertCallQuery("LET n=$seed RETURN * UNION ALL FOR n IN $values RETURN * NEXT RETURN SUM(n) AS answer", "[15]", parameters);
        await AssertCallQuery("LET seed=$seed CALL { RETURN * UNION ALL RETURN * NEXT RETURN SUM(seed) AS valueColumn } RETURN valueColumn AS answer", "[20]", parameters);
        await AssertCallQuery("FOR n IN $values RETURN * LIMIT $seed UNION ALL LET n=1 RETURN * NEXT RETURN SUM(n) AS answer", "[6]", parameters);
        await AssertCallQuery("LET n=$missing RETURN * UNION ALL LET n=2 RETURN * NEXT RETURN n AS answer", "ERROR", parameters);
    }

    private async Task AssertCallQuery(string query, string expected, Dictionary<string, object>? parameters = null)
    {
        _directory = NewDirectory();
        await using var host = EntityForgeDbServer.CreateBuilder().UseLocalStorage(_directory).UsePropertyGraphProfile()
            .ConfigureWebHost(web => web.UseUrls("http://127.0.0.1:0")).Build();
        await host.StartAsync();
        using var client = Client(host);
        using var response = await client.PostAsJsonAsync("/v1/graph/gql/query", new
        {
            query,
            parameters
        });
        if (expected == "ERROR")
        {
            Assert.AreEqual(HttpStatusCode.BadRequest, response.StatusCode, await response.Content.ReadAsStringAsync());
            return;
        }
        Assert.AreEqual(HttpStatusCode.OK, response.StatusCode, await response.Content.ReadAsStringAsync());
        var result = await response.Content.ReadFromJsonAsync<JsonElement>();
        foreach (var row in result.GetProperty("matches").EnumerateArray())
        {
            CollectionAssert.AreEqual(new[] { "answer" }, row.GetProperty("bindings").EnumerateObject().Select(property => property.Name).ToArray());
        }
        using var wanted = JsonDocument.Parse(expected);
        CollectionAssert.AreEquivalent(wanted.RootElement.EnumerateArray().Select(ScalarKey).ToArray(),
            result.GetProperty("matches").EnumerateArray().Select(row => ScalarKey(row.GetProperty("bindings").GetProperty("answer"))).ToArray());
    }
