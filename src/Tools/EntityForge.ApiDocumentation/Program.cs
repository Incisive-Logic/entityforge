using System.Text.Json;
using System.Xml.Linq;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

// Supplement the staged XML only. Never rewrite compiler inputs, generated sources,
// package XML or existing authored explanations. Unknown members remain audit gaps.
if (args.Length != 2)
{
    throw new ArgumentException("Usage: ApiDocumentation <repository-root> <staged-documentation-directory>");
}

string root = Path.GetFullPath(args[0]);
string staging = Path.GetFullPath(args[1]);
using var configuration = JsonDocument.Parse(File.ReadAllText(Path.Combine(root, "docfx.json")));
string[] projects = configuration.RootElement.GetProperty("metadata")[0].GetProperty("src")[0]
    .GetProperty("files").EnumerateArray().Select(value => value.GetString()!).ToArray();
string[] references = ((string)AppContext.GetData("TRUSTED_PLATFORM_ASSEMBLIES")!).Split(Path.PathSeparator)
    .Concat(Directory.GetFiles(staging, "*.dll"))
    .GroupBy(Path.GetFileName, StringComparer.OrdinalIgnoreCase).Select(group => group.First()).ToArray();
int total = 0;
foreach (string project in projects)
{
    string name = Path.GetFileNameWithoutExtension(project);
    string directory = Path.GetDirectoryName(Path.Combine(root, project))!;
    var trees = Directory.GetFiles(directory, "*.cs", SearchOption.AllDirectories)
        .Where(path => !path.Split(Path.DirectorySeparatorChar).Any(part => part is "obj" or "bin"))
        .Select(path => CSharpSyntaxTree.ParseText(File.ReadAllText(path),
            new CSharpParseOptions(LanguageVersion.Preview), path)).ToList();
    trees.Add(CSharpSyntaxTree.ParseText("global using System; global using System.Collections.Generic; global using System.IO; global using System.Linq; global using System.Net.Http; global using System.Threading; global using System.Threading.Tasks;", new CSharpParseOptions(LanguageVersion.Preview)));
    var compilation = CSharpCompilation.Create(name, trees,
        references.Where(path => Path.GetFileNameWithoutExtension(path) != name)
            .Select(path => MetadataReference.CreateFromFile(path)),
        new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary));
    var binaryReference = MetadataReference.CreateFromFile(Path.Combine(staging, name + ".dll"));
    var binaryCompilation = compilation.AddReferences(binaryReference);
    var binary = (IAssemblySymbol)binaryCompilation.GetAssemblyOrModuleSymbol(binaryReference)!;
    var emittedIds = Types(binary.GlobalNamespace).SelectMany(type => new ISymbol[] { type }.Concat(type.GetMembers()))
        .Where(Visible).Select(symbol => symbol.GetDocumentationCommentId()).Where(id => id is not null).ToHashSet();
    string xmlPath = Path.Combine(staging, name + ".xml");
    var document = XDocument.Load(xmlPath);
    var members = document.Root!.Element("members")!;
    var existing = members.Elements("member").ToDictionary(member => (string)member.Attribute("name")!);
    int count = 0;
    foreach (var type in Types(compilation.Assembly.GlobalNamespace))
    {
        bool protobuf = type.DeclaringSyntaxReferences.Any(reference =>
        {
            string source = reference.SyntaxTree.GetText().ToString();
            return source.Contains("<auto-generated>", StringComparison.Ordinal)
                && source.Contains("Generated by the protocol buffer compiler", StringComparison.Ordinal);
        });
        foreach (ISymbol symbol in new ISymbol[] { type }.Concat(type.GetMembers()))
        {
            if (!Visible(symbol))
            {
                continue;
            }
            string? id = symbol.GetDocumentationCommentId();
            if (id is null || !emittedIds.Contains(id) || existing.ContainsKey(id))
            {
                continue;
            }
            string? summary = Describe(symbol, type, protobuf);
            if (summary is null)
            {
                continue;
            }
            var entry = new XElement("member", new XAttribute("name", id), new XElement("summary", summary));
            entry.Add(new XElement("remarks", protobuf
                ? "Generated Protocol Buffers wire API. Use the authored client and codec APIs for application operations; this description covers serialization mechanics."
                : "Compiler-supplied API. This description covers the generated language behavior; see the containing type for its application contract."));
            members.Add(entry);
            existing.Add(id, entry);
            count++;
        }
    }
    string supplementPath = Path.Combine(root, "docs", "api-supplements", name + ".xml");
    if (File.Exists(supplementPath))
    {
        foreach (var entry in XDocument.Load(supplementPath).Root!.Elements("member"))
        {
            string id = (string)entry.Attribute("name")!;
            if (!emittedIds.Contains(id))
            {
                throw new InvalidDataException($"Supplement refers to an API absent from {name}: {id}");
            }
            if (!existing.ContainsKey(id))
            {
                members.Add(new XElement(entry));
                existing.Add(id, entry);
                count++;
            }
        }
    }
    document.Save(xmlPath);
    total += count;
    Console.WriteLine($"{name}: {count} supplemental descriptions");
}
Console.WriteLine($"Added {total} descriptions to staged XML; authored and generated source files were not modified.");

static IEnumerable<INamedTypeSymbol> Types(INamespaceOrTypeSymbol parent)
{
    foreach (var member in parent.GetMembers())
    {
        if (member is INamespaceSymbol space)
        {
            foreach (var nested in Types(space))
            {
                yield return nested;
            }
        }
        else if (member is INamedTypeSymbol type)
        {
            yield return type;
            foreach (var nested in Types(type))
            {
                yield return nested;
            }
        }
    }
}

static bool Visible(ISymbol symbol)
{
    for (ISymbol? current = symbol; current is not null && current is not INamespaceSymbol; current = current.ContainingType)
    {
        if (current.DeclaredAccessibility is not (Accessibility.Public or Accessibility.Protected or Accessibility.ProtectedOrInternal))
        {
            return false;
        }
    }
    return true;
}

static string? Describe(ISymbol symbol, INamedTypeSymbol type, bool protobuf)
{
    if (symbol is IMethodSymbol method && (symbol.IsImplicitlyDeclared || protobuf))
    {
        if (method.MethodKind == MethodKind.Constructor)
        {
            return method.Parameters.Length == 0
                ? $"Initializes a new {type.Name} instance using its default field and property initialization."
                : protobuf && method.Parameters.Length == 1
                    ? $"Creates a deep copy of the supplied {type.Name} Protocol Buffers message."
                    : type.IsRecord && method.Parameters.Length == 1
                        && SymbolEqualityComparer.Default.Equals(method.Parameters[0].Type, type)
                        ? "Initializes a record copy, copying field values without deep-cloning referenced objects."
                    : type.TypeKind == TypeKind.Delegate
                        ? "Creates a delegate bound to the supplied target and method pointer."
                        : null;
        }
        if (type.TypeKind == TypeKind.Delegate)
        {
            return method.Name switch
            {
                "Invoke" => "Invokes the registered delegate target(s) synchronously with the supplied arguments.",
                "BeginInvoke" or "EndInvoke" => "Legacy asynchronous delegate entrypoint; unsupported by modern .NET. Invoke the delegate directly or use an asynchronous API instead.",
                _ => null
            };
        }
        if (type.IsRecord || protobuf)
        {
            return method.Name switch
            {
                "Equals" or "op_Equality" => protobuf
                    ? "Compares Protocol Buffers message values, including repeated fields and retained unknown fields."
                    : "Tests record value equality using the equality comparer for each record field; collection fields retain their own equality semantics.",
                "op_Inequality" => "Returns the negation of record value equality.",
                "GetHashCode" => "Computes an in-process hash consistent with value equality. Do not persist it as a stable identifier.",
                "ToString" => protobuf
                    ? "Returns the Protocol Buffers diagnostic JSON representation of this message."
                    : "Returns the compiler-generated diagnostic representation of the record and its printable members; this is not a serialization contract.",
                "Deconstruct" => "Copies the positional record properties into the corresponding output parameters.",
                "PrintMembers" => "Appends the record's printable members to the diagnostic string builder and reports whether any members were printed.",
                "Clone" when protobuf => "Creates a deep copy of this Protocol Buffers message.",
                "CalculateSize" when protobuf => "Calculates the number of bytes needed to encode this message in Protocol Buffers wire format.",
                "WriteTo" when protobuf => "Writes this message in Protocol Buffers wire format to the supplied output.",
                "MergeFrom" when protobuf => "Merges the supplied message or encoded input using Protocol Buffers merge semantics; repeated fields are appended rather than replaced.",
                _ when protobuf && method.Name.StartsWith("Clear", StringComparison.Ordinal) => "Clears the indicated optional field or oneof selection, removing its presence from the message.",
                _ => null
            };
        }
    }
    if (type.IsRecord && symbol.IsImplicitlyDeclared && symbol is IPropertySymbol { Name: "EqualityContract" })
    {
        return "Gets the runtime record type used to distinguish equality between records in the inheritance hierarchy.";
    }
    if (!protobuf)
    {
        return null;
    }
    if (symbol is INamedTypeSymbol named)
    {
        return named.TypeKind == TypeKind.Enum
            ? $"Wire discriminants for {named.Name}; numeric values are defined by the Protocol Buffers schema."
            : $"Generated Protocol Buffers wire representation for {named.Name}.";
    }
    if (symbol is IFieldSymbol field && type.TypeKind == TypeKind.Enum)
    {
        return $"Selects the {field.Name} wire variant (numeric value {field.ConstantValue}).";
    }
    if (symbol is IPropertySymbol property)
    {
        if (property.Name == "Parser")
        {
            return "Gets the reusable Protocol Buffers parser for this message type.";
        }
        if (property.Name == "Descriptor")
        {
            return "Gets the schema descriptor for this Protocol Buffers message.";
        }
        var number = type.GetMembers(property.Name + "FieldNumber").OfType<IFieldSymbol>().SingleOrDefault();
        if (number is not null)
        {
            return $"{(property.SetMethod is null ? "Gets" : "Gets or sets")} the {property.Name} payload (Protocol Buffers field {number.ConstantValue})."
                + (property.Type.Name == "RepeatedField" ? " The returned collection is mutable; add or remove elements to change the repeated field." : "");
        }
        if (property.Name.StartsWith("Has", StringComparison.Ordinal))
        {
            return "Indicates whether the optional field is explicitly present, independently of its default value.";
        }
        if (property.Name.EndsWith("Case", StringComparison.Ordinal))
        {
            return "Identifies the currently selected oneof alternative, or None when no alternative is present.";
        }
    }
    return null;
}
