namespace EntityForge.Db.Rdf;

public static partial class RdfSparql
{
    internal static string IsolateModifyTemplateBlankLabels(string update, out Dictionary<string, string> labels)
    {
        var (body, prefixes) = ParseProlog(update);
        string[] tokens = Tokenize(body, prefixes);
        var occupied = tokens.ToHashSet(StringComparer.Ordinal);
        var identities = new Dictionary<string, string>(StringComparer.Ordinal);
        labels = new(StringComparer.Ordinal);
        int depth = 0, next = 0;
        bool insert = false;
        for (int i = 0; i < tokens.Length; i++)
        {
            if (depth == 0)
            {
                insert = tokens[i].Equals("INSERT", StringComparison.OrdinalIgnoreCase) || (insert && tokens[i] == "{");
            }
            if (tokens[i] == "{")
            {
                depth++;
            }
            else if (tokens[i] == "}")
            {
                depth--;
            }
            else if (insert && depth > 0 && tokens[i].StartsWith("_:", StringComparison.Ordinal))
            {
                // The validation parser applies query blank-label scope to templates.
                // Give each occurrence a collision-free label only during validation;
                // unify occurrences before native template instantiation. Keep a
                // validation alias as the identity: the original label may collide
                // with a label generated by the parser for an anonymous node.
                string alias;
                do
                {
                    alias = "_:entityforgeTemplate" + next++;
                }
                while (!occupied.Add(alias));
                if (!identities.TryGetValue(tokens[i], out string? identity))
                {
                    identity = alias;
                    identities.Add(tokens[i], identity);
                }
                labels.Add(alias, identity);
                tokens[i] = alias;
            }
        }
        return labels.Count == 0 ? update : CanonicalUpdateProlog(update) + string.Join(" ", tokens);
    }

    internal static string RestoreModifyTemplateBlankLabels(string body, IReadOnlyDictionary<string, string> labels)
    {
        if (labels.Count == 0)
        {
            return body;
        }
        return string.Join(" ", Tokenize(body, new Dictionary<string, string>()).Select(token => labels.TryGetValue(token, out string? label) ? label : token));
    }

    internal static string NormalizeModifyTemplateQuads(string update)
    {
        var (body, prefixes) = ParseProlog(update);
        string[] tokens = Tokenize(body, prefixes);
        var output = new List<string>();
        bool changed = false;
        for (int i = 0; i < tokens.Length; i++)
        {
            output.Add(tokens[i]);
            if (!(tokens[i].Equals("DELETE", StringComparison.OrdinalIgnoreCase) ||
                  tokens[i].Equals("INSERT", StringComparison.OrdinalIgnoreCase)) ||
                i + 1 >= tokens.Length || tokens[i + 1] != "{")
            {
                continue;
            }

            // The dependency parser represents default triples after GRAPH as an
            // extra group, then rejects that representation as a nested template.
            // Quad templates are sets: collect default triples ahead of GRAPH blocks.
            // Only rearrange the flat standard Quads grammar; leave other structures
            // untouched so the parser still rejects nested groups and query clauses.
            int start = ++i, cursor = i + 1;
            var defaults = new List<string>();
            var graphs = new List<string>();
            bool seenGraph = false, reordered = false;
            while (cursor < tokens.Length && tokens[cursor] != "}")
            {
                if (tokens[cursor] == "{")
                {
                    return update;
                }
                if (tokens[cursor].Equals("GRAPH", StringComparison.OrdinalIgnoreCase))
                {
                    if (cursor + 2 >= tokens.Length || tokens[cursor + 2] != "{")
                    {
                        return update;
                    }
                    int end = cursor + 3;
                    while (end < tokens.Length && tokens[end] != "}")
                    {
                        if (tokens[end] == "{")
                        {
                            return update;
                        }
                        end++;
                    }
                    if (end == tokens.Length)
                    {
                        return update;
                    }
                    graphs.AddRange(tokens[cursor..(end + 1)]);
                    cursor = end + 1;
                    if (cursor < tokens.Length && tokens[cursor] == ".")
                    {
                        cursor++;
                    }
                    seenGraph = true;
                    continue;
                }
                if (seenGraph)
                {
                    reordered = true;
                    if (defaults.Count != 0 && defaults[^1] != ".")
                    {
                        defaults.Add(".");
                    }
                    seenGraph = false;
                }
                defaults.Add(tokens[cursor++]);
            }
            if (cursor == tokens.Length)
            {
                return update;
            }
            if (reordered)
            {
                output.Add("{");
                output.AddRange(defaults);
                if (defaults.Count != 0 && defaults[^1] != ".")
                {
                    output.Add(".");
                }
                output.AddRange(graphs);
                output.Add("}");
                changed = true;
            }
            else
            {
                output.AddRange(tokens[start..(cursor + 1)]);
            }
            i = cursor;
        }
        return changed ? CanonicalUpdateProlog(update) + string.Join(" ", output) : update;
    }
}
